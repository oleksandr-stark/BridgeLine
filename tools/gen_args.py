#!/usr/bin/env python3
"""Generates src/05_args.jsx: for every command, the argument names its code reads (a.x / a["x"] in the def body and in
helper functions it passes `a` to). The panel warns about any other argument ("did you mean ...") instead of silently
ignoring a typo. Run by build.sh before the files are joined; the output is generated, do not edit it."""
import glob, os, re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = sorted(f for f in glob.glob(os.path.join(ROOT, "src", "*.jsx")) if not f.endswith("05_args.jsx"))
KEY = re.compile(r"""\ba\.([A-Za-z_$][\w$]*)|\ba\[\s*["']([^"']+)["']\s*\]""")
ALWAYS = ["_retried"]          # set by the client


def body_at(text, start):
    """Text of the {...} block that starts at the first '{' after start (strings and comments are not special-cased)."""
    i = text.index("{", start)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[i:j + 1]
    return text[i:]


DYN = re.compile(r"\ba\[\s*[A-Za-z_$][\w$.\[\]]*\s*\]")          # a[k], a[tf[i]]: keys from a list or a map
FORWARD = re.compile(r"for\s*\(\s*var\s+\w+\s+in\s+a\s*\)")      # every key passed on


def keys(body):
    ks = {m.group(1) or m.group(2) for m in KEY.finditer(body)}
    if FORWARD.search(body):
        return ks | {"*"}
    if DYN.search(body):
        lists = re.findall(r"\[\s*((?:\"\w+\"\s*,?\s*)+)\]", body)
        names = set(re.findall(r"\"(\w+)\"", " ".join(lists)))
        names |= set(re.findall(r"[{,]\s*(\w+)\s*:", body))          # keys of object literals (maps)
        ks |= names if names else {"*"}
    return ks


def main():
    code = "\n".join(open(f, encoding="utf-8").read() for f in SRC)
    # helpers with a parameter named `a`
    helpers = {}
    for m in re.finditer(r"^function\s+(\w+)\s*\(([^)]*)\)", code, re.M):
        params = [p.strip() for p in m.group(2).split(",")]
        if "a" in params:
            helpers[m.group(1)] = keys(body_at(code, m.end()))
    # helpers that pass `a` on to other helpers (one level is enough here, two for safety)
    for _ in range(2):
        for name in list(helpers):
            m = re.search(r"^function\s+%s\s*\(" % name, code, re.M)
            b = body_at(code, m.end())
            for h in helpers:
                if h != name and re.search(r"\b%s\s*\([^;]*\ba\b" % h, b):
                    helpers[name] |= helpers[h]
    out = {}
    for m in re.finditer(r'^def\("(\w+)",', code, re.M):
        b = body_at(code, code.index("function", m.end()))
        ks = keys(b)
        for h, hk in helpers.items():
            if re.search(r"\b%s\s*\([^;]*\ba\b" % h, b):
                ks |= hk
        out[m.group(1)] = sorted(ks | set(ALWAYS))
    lines = ["// ================================================================ GENERATED by tools/gen_args.py - do not edit",
             "// argument names each command reads; RB.run warns about others", "RB.ARGS = {"]
    names = sorted(out)
    for i, n in enumerate(names):
        lines.append('    %s: "%s"%s' % (n, " ".join(out[n]), "," if i < len(names) - 1 else ""))
    lines.append("};")
    with open(os.path.join(ROOT, "src", "05_args.jsx"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("args: %d commands" % len(names))


if __name__ == "__main__":
    main()
